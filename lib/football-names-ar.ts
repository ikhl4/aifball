function normalizeName(name: string): string {
  return name.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/\s+/g, ' ');
}

const NORMALIZED_NAMES = new Map(Object.entries(ARABIC_NAMES).map(([name, translated]) => [normalizeName(name), translated]));

export function footballNameInArabic(name: string): string | null {
  return NORMALIZED_NAMES.get(normalizeName(name)) || null;
}

export function footballGroupInArabic(name: string): string {
  const labels: Record<string, string> = {
    'East Region': 'منطقة الشرق', 'West Region': 'منطقة الغرب',
    'Eastern Conference': 'القسم الشرقي', 'Western Conference': 'القسم الغربي',
    'League Phase': 'مرحلة الدوري', 'Overall': 'الترتيب العام',
    'Regular Season': 'المرحلة المنتظمة', 'First Phase': 'المرحلة الأولى',
    'Second Phase': 'المرحلة الثانية', 'Championship Round': 'مجموعة التتويج',
    'Relegation Round': 'مجموعة تفادي الهبوط',
  };
  return name.split(' / ').map(part => {
    const label = part.trim();
    if (labels[label]) return labels[label];
    const leagueGroup = label.match(/^League ([A-D]), Group ([A-Z0-9]+)$/i);
    if (leagueGroup) return `المستوى ${leagueGroup[1]}، المجموعة ${leagueGroup[2]}`;
    const league = label.match(/^League ([A-D])$/i);
    if (league) return `المستوى ${league[1]}`;
    const group = label.match(/\bGroup ([A-Z0-9]+)$/i);
    if (group) return `المجموعة ${group[1]}`;
    return label;
  }).join(' / ');
}
